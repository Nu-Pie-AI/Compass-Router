/**
 * Team Size Match for Offerings (0-10 points)
 * Uses icpTeamSize field directly
 */
export function scoreTeamSizeOffering(
  offering: AdvisorOfferingData,
  userTeamSize?: string
): number {
  if (!userTeamSize || !offering.icpTeamSize) return 0;

  const offeringTeamSize = offering.icpTeamSize.toLowerCase();
  const userSize = userTeamSize.toLowerCase();

  // Define team size ranges for comparison
  const sizeRanges = [
    ['1-5', 'solo', 'solopreneur', 'freelancer'],
    ['6-20', 'small team', 'startup'],
    ['21-50', 'growing team', 'small business'],
    ['51-200', 'mid-size', 'medium business'],
    ['201+', 'large', 'enterprise'],
  ];

  const offeringRange = sizeRanges.findIndex((range) =>
    range.some((term) => offeringTeamSize.includes(term))
  );
  const userRange = sizeRanges.findIndex((range) =>
    range.some((term) => userSize.includes(term))
  );

  if (offeringRange === -1 || userRange === -1) return 0;

  const rangeDiff = Math.abs(offeringRange - userRange);

  if (rangeDiff === 0) return 10; // Exact match
  if (rangeDiff === 1) return 7; // Adjacent range
  if (rangeDiff === 2) return 3; // Within 2 ranges
  return 0;
}

/**
 * Budget Match for Offerings (0-15 points)
 * Uses icpBudget and startingPrice fields
 */
export function scoreBudgetOffering(
  offering: AdvisorOfferingData,
  userBudget?: string
): number {
  if (!userBudget) return 0;

  // Extract numeric value from user budget (e.g., "$50-200/mo" -> 200)
  const userBudgetMatch = userBudget.match(/\d+/g);
  if (!userBudgetMatch) return 0;

  const userMaxBudget = Math.max(...userBudgetMatch.map(Number));
  const offeringPrice = offering.startingPrice;

  if (!offeringPrice) return 0;

  // Free offerings always match budget
  if (offering.pricingModel?.toLowerCase() === 'free') return 15;

  // Check if freemium and has free option
  if (offering.pricingModel?.toLowerCase() === 'freemium' && offering.hasFreeTrial) {
    return 15;
  }

  // Compare pricing
  if (offeringPrice <= userMaxBudget) return 15; // Within budget
  if (offeringPrice <= userMaxBudget * 1.2) return 10; // Within 20% over
  if (offeringPrice <= userMaxBudget * 1.5) return 5; // Within 50% over
  return 0;
}

/**
 * Target Customer Match for Offerings (0-5 points)
 * Uses icpCompanyStage field
 */
export function scoreTargetCustomerOffering(
  offering: AdvisorOfferingData,
  userCompanyStage?: string
): number {
  if (!userCompanyStage) return 0;

  // Check if offering's ICP fields match user stage
  // This is a simplified scoring - can be enhanced based on available data
  if (offering.icpIndustry && offering.icpIndustry.length > 0) {
    return 3; // Partial credit if ICP is defined
  }

  return 0;
}

/**
 * Batch score multiple offerings
 */
export async function scoreOfferings(
  offerings: AdvisorOfferingData[],
  userContext: UserContext,
  useCaseSimilarityScores?: Map<string, number> // offeringId -> similarity score (0-1)
): Promise<ScoredOffering[]> {
  const scored = await Promise.all(
    offerings.map((offering) =>
      scoreOffering(
        offering,
        userContext,
        useCaseSimilarityScores?.get(offering.id)
      )
    )
  );

  // Sort by match score (descending)
  return scored.sort((a, b) => b.matchScore - a.matchScore);
}
