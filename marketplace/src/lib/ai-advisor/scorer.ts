import {
  AdvisorOfferingData,
  UserContext,
  ScoredOffering,
  ScoreBreakdown,
} from './types';

/**
 * Score an offering against user context using 6-component algorithm
 * Total: 100 points
 * - Embedding Similarity: 0-35 (DOMINANT - deterministic semantic match)
 * - Category Match: 0-25
 * - Budget Match: 0-15
 * - Team Size Match: 0-10
 * - Rating Score: 0-10
 * - Target Customer Match: 0-5
 */
export async function scoreOffering(
  offering: AdvisorOfferingData,
  userContext: UserContext,
  embeddingSimilarityScore?: number // Pre-computed cosine similarity (0-1)
): Promise<ScoredOffering> {
  const scoreBreakdown: ScoreBreakdown = {
    categoryMatch: scoreCategoryMatchOffering(offering, userContext.detectedCategory),
    teamSizeMatch: scoreTeamSizeOffering(offering, userContext.teamSize),
    budgetMatch: scoreBudgetOffering(offering, userContext.budget),
    useCaseMatch: scoreContextFitOffering(
      offering,
      userContext,
      embeddingSimilarityScore
    ),
    targetCustomerMatch: scoreTargetCustomerOffering(offering, userContext.companyStage),
    ratingScore: scoreRating(offering.averageRating),
  };

  const matchScore = Object.values(scoreBreakdown).reduce(
    (sum, score) => sum + score,
    0
  );

  return {
    offering,
    matchScore,
    scoreBreakdown,
    reasoning: '', // Will be generated by OpenAI
  };
}

/**
 * Category Match for Offerings (0-25 points)
 * - Exact match with primaryFunction: 25 points
 * - Match in categories array: 20 points
 * - Partial match (parent/child category): 10 points
 * - No match: 0 points
 */
export function scoreCategoryMatchOffering(
  offering: AdvisorOfferingData,
  detectedCategory: string
): number {
  const normalizedCategory = detectedCategory.toLowerCase().trim();

  // Exact match with primaryFunction
  if (offering.primaryFunction?.toLowerCase() === normalizedCategory) {
    return 25;
  }

  // Match in categories array
  const categoryMatch = offering.categories.some(
    (cat) =>
      cat.slug.toLowerCase() === normalizedCategory ||
      cat.name.toLowerCase() === normalizedCategory
  );
  if (categoryMatch) {
    return 20;
  }

  // Partial match (contains category keyword)
  const hasPartialMatch = offering.categories.some(
    (cat) =>
      cat.slug.toLowerCase().includes(normalizedCategory) ||
      normalizedCategory.includes(cat.slug.toLowerCase()) ||
      cat.name.toLowerCase().includes(normalizedCategory) ||
      normalizedCategory.includes(cat.name.toLowerCase())
  );
  if (hasPartialMatch) {
    return 10;
  }

  return 0;
}


/**
 * Use Case Match (0-20 points)
 * This score is computed via semantic similarity using OpenAI embeddings
 * Comparing user's problem description with Q2 "Top 5 use cases" answer
 *
 * This function is a placeholder - actual computation happens in recommendation API
 * using OpenAI embeddings or completion API
 */
export function scoreUseCaseMatch(
  similarityScore: number // 0-1 from OpenAI
): number {
  // Convert 0-1 similarity to 0-20 points
  return Math.round(similarityScore * 20);
}

function scoreContextFitOffering(
  offering: AdvisorOfferingData,
  userContext: UserContext,
  embeddingSimilarityScore?: number
) {
  const baseScore = embeddingSimilarityScore ? embeddingSimilarityScore * 25 : 0;
  let contextBonus = 0;

  if (userContext.useCases && userContext.useCases.length > 0) {
    const offeringUseCaseText = [
      ...offering.useCases,
      ...offering.painPointsSolved,
      ...offering.features.map((feature) => feature.name),
      ...offering.features.map((feature) => feature.description),
    ]
      .join(' ')
      .toLowerCase();

    const useCaseHits = userContext.useCases.filter((useCase) =>
      offeringUseCaseText.includes(useCase.toLowerCase())
    ).length;

    contextBonus += Math.min(7, useCaseHits * 3);
  }

  if (userContext.integrations && userContext.integrations.length > 0) {
    const offeringIntegrationText = [
      ...offering.integrations,
      ...offering.features.map((feature) => feature.name),
      ...offering.features.map((feature) => feature.description),
    ]
      .join(' ')
      .toLowerCase();

    const integrationHits = userContext.integrations.filter((integration) =>
      offeringIntegrationText.includes(integration.toLowerCase())
    ).length;

    contextBonus += Math.min(3, integrationHits * 1.5);
  }

  return Math.min(35, baseScore + contextBonus);
}

/**
 * Rating Score (0-10 points)
 * Based on product's average rating
 * - 4.5+ stars: 10 points
 * - 4.0-4.4 stars: 8 points
 * - 3.5-3.9 stars: 6 points
 * - 3.0-3.4 stars: 4 points
 * - 2.5-2.9 stars: 2 points
 * - < 2.5 stars: 0 points
 */
export function scoreRating(averageRating: number): number {
  if (averageRating >= 4.5) return 10;
  if (averageRating >= 4.0) return 8;
  if (averageRating >= 3.5) return 6;
  if (averageRating >= 3.0) return 4;
  if (averageRating >= 2.5) return 2;
  return 0;
}

